#!/usr/bin/env python3
"""
Kagome lattice on a torus: sites, nearest-neighbour bonds, triangles, hexagons and lattice symmetries.

Geometry.  The kagome lattice is the triangular Bravais lattice with primitive vectors a1 = (1, 0), a2 = (1/2, sqrt(3)/2) (angle 60 degrees) and
three sites per unit cell R = x a1 + y a2 (x, y integers):
        A(R) = R ,     B(R) = R + a1/2 ,     C(R) = R + a2/2 .
Up triangle of the cell R:    A(R), B(R), C(R).             Down triangle:    B(R), A(R + a1), C(R + a1 - a2).
Every site lies in one up and one down triangle, so there are 2N nearest-neighbour bonds (6 per cell) and every site has 4 neighbours.
The hexagon centred at R + (a1 + a2)/2 has the six sites C(R + a1), C(R), B(R + a2), B(R), A(R + a1), A(R + a2).

Torus.  A cluster is the quotient of the lattice by the sublattice generated by two spanning vectors T1 = (n1, n2), T2 = (m1, m2) (integer
coordinates in the basis a1, a2; basis=120 means that a2 is the primitive vector at 120 degrees from a1, as in some papers); it has
|n1 m2 - n2 m1| cells and N = 3 |n1 m2 - n2 m1| sites.  L1 x L2 cells is Torus((L1, 0), (0, L2)).  Site index = 3 * (cell index) + sublattice (A, B, C = 0, 1, 2).
Very small tori can contain the same pair of sites twice (e.g. one cell: the up and the down bond between the same two sites); such bonds
are merged into one bond whose weight is the sum of the couplings, which is exactly the same Hamiltonian.

Symmetry.  translations() are the N/3 translations of the torus; point_group() adds the rotations and reflections about a hexagon centre (up to
12 operations, those that map the sublattice generated by T1, T2 to itself).  Both are returned as site permutations.

Usage:  python3 kagome_lattice.py 12            # summary of the N = 12 torus (cluster names: see CLUSTERS)
        python3 kagome_lattice.py 3 3           # L1 x L2 cells
"""
import math
import sys

import numpy as np

SQ3 = math.sqrt(3.0)

# Clusters of Laeuchli, Sudan, Soerensen, PRB 83, 212401 (2011), Table I, as spanning vectors (n1, n2), (m1, m2) in the basis a1, a2.
# Which angle between a1 and a2 the paper uses was fixed by comparing exact ground-state energies: with the 60-degree basis used here, exact diagonalisation
# (kagome_gaussian_S1.py <cluster> --ed) reproduces the paper's totals for N = 12, 18a, 18b and 24 to 9 digits (the dictionary LITERATURE_ED there);
# the clusters with N >= 27 are too large for this exact diagonaliser and their literature values are quoted unverified.
CLUSTERS = {
    "12": ((2, 0), (0, 2)), "18a": ((2, -1), (0, 3)), "18b": ((2, -2), (-2, -1)), "24": ((1, 2), (-3, 2)),
    "27a": ((2, 1), (-3, 3)), "27b": ((3, 0), (0, 3)), "30": ((2, 1), (-2, 4)),
    "36a": ((-2, 3), (4, 0)), "36b": ((3, 0), (-3, 4)), "36c": ((3, 0), (-1, 4)), "36d": ((4, -2), (-2, 4)),
}
PAPER_BASIS = 60


def _egcd(a, b):
    """(g, u, v) with u a + v b = g = gcd(a, b) >= 0."""
    if b == 0:
        return (abs(a), (1 if a >= 0 else -1), 0)
    g, u, v = _egcd(b, a % b)
    return g, v, u - (a // b) * v


class Torus:
    def __init__(self, T1, T2, basis=60, name=None):
        if basis not in (60, 120):
            raise ValueError("basis must be 60 or 120 (angle between the primitive vectors a1, a2 in degrees)")
        t1, t2 = [tuple(int(c) for c in T) for T in (T1, T2)]
        if basis == 120:                                       # a2(120) = a2(60) - a1
            t1, t2 = [(n1 - n2, n2) for n1, n2 in (t1, t2)]
        (a, b), (c, d) = t1, t2
        det = a * d - b * c
        if det == 0:
            raise ValueError("the two spanning vectors are parallel")
        # Hermite normal form of the sublattice: basis (p, q), (0, r), 0 <= q < r
        g, u, v = _egcd(a, c)
        self._p = g
        qq = u * b + v * d
        self._r = abs(det) // g
        self._q = qq % self._r
        self.T1, self.T2, self.name = t1, t2, name
        self.ncell = abs(det)
        self.N = 3 * self.ncell
        # cell representatives and index
        self.cells = [(x, y) for x in range(self._p) for y in range(self._r)]
        self.cell_index = {c_: i for i, c_ in enumerate(self.cells)}
        assert len(self.cells) == self.ncell
        self._build()

    # ---------------------------------------------------------------------------------------------- reduction and indexing
    def reduce(self, x, y):
        """Canonical representative (x', y') of the cell (x, y) modulo the sublattice."""
        k = x // self._p
        x2, y2 = x - k * self._p, y - k * self._q
        return x2, y2 % self._r

    def site(self, x, y, s):
        return 3 * self.cell_index[self.reduce(x, y)] + s

    def in_sublattice(self, x, y):
        return self.reduce(x, y) == (0, 0)

    # ---------------------------------------------------------------------------------------------- geometry
    def _build(self):
        N = self.N
        S = self.site
        pairs = {}                                          # (i, j) i < j -> [n_up, n_down]
        tri, hexa = [], []
        for (x, y) in self.cells:
            A, B, C = S(x, y, 0), S(x, y, 1), S(x, y, 2)
            for i, j in ((A, B), (B, C), (C, A)):
                pairs.setdefault((min(i, j), max(i, j)), [0, 0])[0] += 1
            for i, j in ((A, S(x - 1, y, 1)), (A, S(x, y - 1, 2)), (B, S(x + 1, y - 1, 2))):
                pairs.setdefault((min(i, j), max(i, j)), [0, 0])[1] += 1
            tri.append(("up", (A, B, C)))
            tri.append(("down", (B, S(x + 1, y, 0), S(x + 1, y - 1, 2))))
            # hexagon around the half-lattice point (2x + 1, 2y + 1)
            pts = [(2, 1), (0, 1), (1, 2), (1, 0), (2, 0), (0, 2)]
            sites, ang = [], []
            for dm, dn in pts:
                m, n = 2 * x + dm, 2 * y + dn
                sites.append(self._site_from_half(m, n))
                px, py = self._half_cart(m - (2 * x + 1), n - (2 * y + 1))
                ang.append(math.atan2(py, px))
            hexa.append(tuple(s_ for _, s_ in sorted(zip(ang, sites))))
        keys = sorted(pairs)
        self.bonds = np.array(keys, dtype=int).reshape(-1, 2)
        self.n_up = np.array([pairs[k][0] for k in keys], float)
        self.n_down = np.array([pairs[k][1] for k in keys], float)
        self.triangles = tri
        self.hexagons = hexa
        self.sublattice = np.arange(N) % 3
        self.positions = np.array([self._cart(self.cells[i // 3], i % 3) for i in range(N)])

    @staticmethod
    def _half_cart(m, n):
        """Cartesian position of the point m a1/2 + n a2/2."""
        return (m / 2.0 + n / 4.0, n * SQ3 / 4.0)

    def _site_from_half(self, m, n):
        """Site at the half-lattice point (m, n) (m a1/2 + n a2/2; (odd, odd) is a hexagon centre, not a site)."""
        pm, pn = m % 2, n % 2
        if (pm, pn) == (1, 1):
            raise ValueError("hexagon centre is not a site")
        return self.site(m // 2, n // 2, {(0, 0): 0, (1, 0): 1, (0, 1): 2}[(pm, pn)])

    @staticmethod
    def _cart(cell, s):
        x, y = cell
        u, v = x + (0.5 if s == 1 else 0.0), y + (0.5 if s == 2 else 0.0)
        return (u + v / 2.0, v * SQ3 / 2.0)

    def couplings(self, J_up=1.0, J_down=1.0):
        """Weights of the merged bonds: J_up * (number of up bonds) + J_down * (number of down bonds)."""
        return J_up * self.n_up + J_down * self.n_down

    @property
    def nbonds(self):
        return len(self.bonds)

    def coordination(self):
        """Number of distinct neighbours of each site (4 on a large torus) and, with multiplicity, 4 always."""
        z = np.zeros(self.N, int)
        for i, j in self.bonds:
            z[i] += 1
            z[j] += 1
        return z

    # ---------------------------------------------------------------------------------------------- symmetries
    def translations(self):
        """List of N/3 site permutations (arrays p with p[i] = image of site i)."""
        out = []
        for (tx, ty) in self.cells:
            p = np.empty(self.N, int)
            for (x, y) in self.cells:
                for s in range(3):
                    p[3 * self.cell_index[(x, y)] + s] = self.site(x + tx, y + ty, s)
            out.append(p)
        return out

    def point_group(self):
        """Permutations of the sites for the rotations / reflections about the hexagon centre (m, n) = (1, 1) that map the torus lattice to itself
        (identity included; at most 12)."""
        rot = lambda u, v: (-v, u + v)                   # rotation by 60 degrees of the half-lattice vector (u, v)
        ref = lambda u, v: (v, u)                        # reflection a1 <-> a2
        ops = []
        for refl in (False, True):
            for k in range(6):
                def op(u, v, k=k, refl=refl):
                    if refl:
                        u, v = ref(u, v)
                    for _ in range(k):
                        u, v = rot(u, v)
                    return u, v
                ops.append(op)
        out = []
        for op in ops:
            # the operation acts on the cell vectors as (x, y) -> op(x, y) (half-lattice vector 2(x, y) -> 2 op(x, y)); the sublattice must be invariant
            if not all(self.in_sublattice(*op(*T)) for T in (self.T1, self.T2)):
                continue
            p = np.empty(self.N, int)
            for (x, y) in self.cells:
                for s in range(3):
                    m, n = 2 * x + (1 if s == 1 else 0), 2 * y + (1 if s == 2 else 0)
                    u, v = op(m - 1, n - 1)
                    p[3 * self.cell_index[(x, y)] + s] = self._site_from_half(u + 1, v + 1)
            out.append(p)
        return out

    def all_symmetries(self):
        """Translations composed with the point-group operations (permutations of the sites)."""
        pg, tr = self.point_group(), self.translations()
        seen, out = set(), []
        for g in pg:
            for t in tr:
                p = t[g]
                key = p.tobytes()
                if key not in seen:
                    seen.add(key)
                    out.append(p)
        return out

    def is_automorphism(self, perm, weights=None):
        """True if the site permutation maps the bond set (with weights) onto itself."""
        w = self.couplings() if weights is None else weights
        idx = {(int(i), int(j)): k for k, (i, j) in enumerate(self.bonds)}
        for k, (i, j) in enumerate(self.bonds):
            a, b = int(perm[i]), int(perm[j])
            kk = idx.get((min(a, b), max(a, b)))
            if kk is None or abs(w[kk] - w[k]) > 1e-12:
                return False
        return True

    # ---------------------------------------------------------------------------------------------- description
    def summary(self):
        z = self.coordination()
        tot = int(round((self.n_up + self.n_down).sum()))
        lines = [f"kagome torus {self.name or ''}: spanning vectors {self.T1}, {self.T2} (basis a1, a2 at 60 degrees),  {self.ncell} cells,  N = {self.N} sites",
                 f"  bonds: {tot} counting multiplicity (= 2N = {2 * self.N}), {self.nbonds} distinct pairs;  distinct neighbours per site: min {z.min()}, max {z.max()}",
                 f"  triangles: {len(self.triangles)} (= 2N/3),  hexagons: {len(self.hexagons)} (= N/3),  translations: {len(self.translations())},  "
                 f"point-group operations that preserve the torus: {len(self.point_group())}"]
        return "\n".join(lines)


def torus_from_name(name, basis=PAPER_BASIS):
    """Torus of a named cluster of CLUSTERS, an integer N (the standard cluster with that many sites), or 'L1xL2'."""
    s = str(name)
    if "x" in s and s.replace("x", "").isdigit():
        l1, l2 = s.split("x")
        return Torus((int(l1), 0), (0, int(l2)), name=s)
    if s in CLUSTERS:
        return Torus(*CLUSTERS[s], basis=basis, name=s)
    cand = [k for k in CLUSTERS if k.rstrip("abcd") == s]
    if len(cand) >= 1:
        k = cand[0]
        return Torus(*CLUSTERS[k], basis=basis, name=k)
    raise ValueError(f"unknown cluster {name!r}: use one of {sorted(CLUSTERS)} or 'L1xL2'")


if __name__ == "__main__":
    a = sys.argv[1:]
    if len(a) == 2 and all(t.lstrip("-").isdigit() for t in a):
        T = Torus((int(a[0]), 0), (0, int(a[1])), name=f"{a[0]}x{a[1]}")
    elif len(a) == 1 and a[0] not in ("-h", "--help"):
        try:
            T = torus_from_name(a[0])
        except ValueError as err:
            raise SystemExit(str(err))
    else:
        raise SystemExit(__doc__)
    print(T.summary())
